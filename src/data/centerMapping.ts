export const canonicalCenterName = (value: string) => {
  const cleanValue = value?.trim() || 'غير محدد'
  const normalizedValue = normalize(cleanValue)
  if (normalizedValue.includes('التعليم المستمر')) return 'مركز التعليم المستمر'
  return aliases[normalizedValue] ?? cleanValue
}

// A center filter sent to ORDS is a list of normalized source aliases. Oracle
// applies the same basic normalization before matching these keys.
export const sourceKeysForCenter = (center: string) => [
  ...new Set([
    normalize(center),
    ...Object.entries(aliases)
      .filter(([, canonical]) => canonical === center)
      .map(([source]) => source),
  ]),
]

export const isCollegeCenter = (value: string) => canonicalCenterName(value).startsWith('كلية ')

export const isCircleOrCenter = (value: string) => {
  const canonical = canonicalCenterName(value)
  return canonical.startsWith('دائرة ') || canonical.startsWith('مركز ')
}

